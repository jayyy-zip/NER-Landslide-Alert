// Representative locations for the 25 monitored NH-27 sections. These are
// interpolated by distance along the OSM centerline above—not between zone
// coordinates—so the markers always follow the road's natural geometry.
const CORRIDOR_COORDINATES = NH27_CORRIDOR_GEOJSON.features[0].geometry.coordinates
const EARTH_RADIUS_KM = 6371
const DEG_TO_RAD = Math.PI / 180

function segmentLengthKm(start, end) {
  const longitudeDistance = (end[0] - start[0]) * DEG_TO_RAD
    * Math.cos(((start[1] + end[1]) / 2) * DEG_TO_RAD)
  const latitudeDistance = (end[1] - start[1]) * DEG_TO_RAD

  return EARTH_RADIUS_KM * Math.hypot(longitudeDistance, latitudeDistance)
}

const CORRIDOR_CUMULATIVE_LENGTHS = CORRIDOR_COORDINATES.reduce((lengths, point, index) => {
  if (index === 0) return [0]
  return [...lengths, lengths[index - 1] + segmentLengthKm(CORRIDOR_COORDINATES[index - 1], point)]
}, [])

const CORRIDOR_LENGTH_KM = CORRIDOR_CUMULATIVE_LENGTHS.at(-1)

function coordinateAtDistance(distanceKm) {
  const endIndex = CORRIDOR_CUMULATIVE_LENGTHS.findIndex(length => length >= distanceKm)
  const index = Math.max(1, endIndex)
  const startDistance = CORRIDOR_CUMULATIVE_LENGTHS[index - 1]
  const endDistance = CORRIDOR_CUMULATIVE_LENGTHS[index]
  const progress = (distanceKm - startDistance) / (endDistance - startDistance)
  const start = CORRIDOR_COORDINATES[index - 1]
  const end = CORRIDOR_COORDINATES[index]

  return {
    lat: Number((start[1] + (end[1] - start[1]) * progress).toFixed(7)),
    lng: Number((start[0] + (end[0] - start[0]) * progress).toFixed(7)),
  }
}

export function alignRiskZonesToCorridor(zones = []) {
  if (zones.length === 0) return []

  return zones.map((zone, index) => ({
    ...zone,
    ...coordinateAtDistance(CORRIDOR_LENGTH_KM * (index + 0.5) / zones.length),
  }))
}
